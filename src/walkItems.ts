// フィッシャー–イェーツでシャッフルしたコピーを返す（元配列は壊さない）
function shuffled<T>(arr: readonly T[]): T[] {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

// 既存の語（exclude）と重複しないランダムなお題を count 個返す
export function randomWords(count: number, exclude: readonly string[] = []): string[] {
  const used = new Set(exclude)
  return shuffled(WALK_ITEMS.filter((w) => !used.has(w))).slice(0, count)
}
